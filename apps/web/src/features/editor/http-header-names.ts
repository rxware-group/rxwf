export const COMMON_HTTP_HEADER_NAMES = HTTP_HEADER_NAMES;

export function filterHttpHeaderNames(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...HTTP_HEADER_NAMES];
  return HTTP_HEADER_NAMES.filter((name) => name.toLowerCase().includes(q));
}

