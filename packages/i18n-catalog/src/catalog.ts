export function normalizeLocaleCode(locale: string): string {
  if (locale === 'en') return 'en-US';
  return locale;
}

export function listLocales(): string[] {
  return Object.keys(bundles);
}

const overrides: Record<string, Record<string, string>> = {};

export function getLocaleBundle(locale: string): Record<string, string> {
  const resolved = normalizeLocaleCode(locale);
  const base = bundles[resolved] ?? bundles['en-US'] ?? {};
  return { ...base, ...(overrides[resolved] ?? overrides[locale] ?? {}) };
}

export function setLocaleOverrides(locale: string, messages: Record<string, string>): void {
  overrides[locale] = { ...(overrides[locale] ?? {}), ...messages };
}
